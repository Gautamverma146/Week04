package com.tit.day06.reflection.intermediate_level.dynamic_method_invocation;

public class MathOperations {
    //method for addition
    public int add(int a, int b) {
        return a + b;
    }
    //method for subtract
    public int subtract(int a, int b) {
        return a - b;
    }
    //method for multiply
    public int multiply(int a, int b) {
        return a * b;
    }
}
